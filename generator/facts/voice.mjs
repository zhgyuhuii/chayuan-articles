// ---------- 段落组装工具 ----------
export function joinProse(r, items, max = 4) {
  // 把要点列表织成一小段自然语言（避免全部 bullet 化；不在已有句读后再加标点）
  const picked = pickN(r, items, Math.min(max, items.length));
  const clean = (s, end) => {
    const t = s.trim().replace(/[。；，、]+$/, '');
    return t + end;
  };
  if (picked.length === 1) return clean(picked[0], '。');
  return picked.map((s, i) => (i === picked.length - 1 ? clean(s, '。') : clean(s, pick(r, ['，', '；'])))).join('');
}
